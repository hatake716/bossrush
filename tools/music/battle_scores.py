from fractions import Fraction


def phrase(text, beats=4):
    result = []
    for bar, line in enumerate(text.split('|')):
        cursor = Fraction(0)
        for token in line.split():
            pitch, _, duration = token.partition(':')
            length = Fraction(duration or '1')
            assert length > 0, token
            result.append((bar * beats + cursor, length, None if pitch == 'r' else int(pitch)))
            cursor += length
        assert cursor == beats, (bar, line, cursor, beats)
    return result


